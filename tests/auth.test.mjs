import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {hashPassword,verifyPassword,digest,requireAdmin,requireSameOrigin,sessionCookie,sessionToken} from '../lib/admin-auth.js';
test('senha com acentos é verificada no servidor e exige configuração válida',async()=>{
 const password='Teste-Çã-1234';
 process.env.ADMIN_PASSWORD_HASH=await hashPassword(password);
 assert.equal(await verifyPassword(password),true);
 assert.equal(await verifyPassword(password.normalize('NFD')),true);
 assert.equal(await verifyPassword('incorreta'),false);
 assert.equal(await verifyPassword(null),false);
 assert.equal(await verifyPassword('a'.repeat(257)),false);
 const token=randomBytes(32).toString('base64url');
 const req={headers:{cookie:'other=1; amorim_admin='+token},method:'GET'};
 let calls=0;
 const sql=async(strings,...values)=>{calls++;assert.match(strings.join('?'),/expires_at>now\(\)/);assert.equal(values[0],digest(token));assert.equal(values[1],digest(process.env.ADMIN_PASSWORD_HASH));return[{token_hash:values[0]}];};
 assert.equal((await requireAdmin(req,sql)).access,'password-session');
 assert.equal(calls,1);
 await assert.rejects(()=>requireAdmin(req,async()=>[]));
 await assert.rejects(()=>requireAdmin({headers:{authorization:'Bearer '+token}},sql));
 await assert.rejects(()=>requireAdmin({headers:{cookie:'amorim_admin=invalid'}},sql));
 await assert.rejects(()=>requireAdmin({...req,method:'POST'},sql));
 assert.equal(calls,1);
 delete process.env.ADMIN_PASSWORD_HASH;
 await assert.rejects(()=>verifyPassword(password),/auth_unconfigured/);
 await assert.rejects(()=>requireAdmin(req,sql),/auth_unconfigured/);
});
test('sessão usa cookie seguro e alterações exigem mesma origem',()=>{
 process.env.VERCEL='1';
 const token=randomBytes(32).toString('base64url');
 assert.match(sessionCookie(token),/^__Host-amorim_admin=/);
 for(const flag of ['HttpOnly','Secure','SameSite=Strict','Path=/','Max-Age=604800'])assert.ok(sessionCookie(token).includes(flag));
 assert.match(sessionCookie(),/Max-Age=0/);
 assert.equal(sessionToken({headers:{cookie:'__Host-amorim_admin='+token}}),token);
 assert.equal(sessionToken({headers:{cookie:'amorim_admin='+token}}),null);
 const headers={origin:'https://amorim-diagnostico-imobiliarias.vercel.app','x-amorim-request':'1'};
 assert.doesNotThrow(()=>requireSameOrigin({headers}));
 assert.throws(()=>requireSameOrigin({headers:{...headers,origin:'https://example.com'}}));
 assert.throws(()=>requireSameOrigin({headers:{origin:headers.origin}}));
 delete process.env.VERCEL;
});
